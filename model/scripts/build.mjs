// Builds the page into dist/ with the family's build: shared/scripts/build.mjs. Only what is this tool's own is here:
// its icons, Draco's decoder packed for the page, and the notices the libraries inside three.js ask to travel with it.
import { buildTool } from '../../shared/scripts/build.mjs';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const three = join(root, 'node_modules/three');

// the Draco decoder that comes with three.js, only the part glTF needs, kept inside the program and loaded only when a
// model asks for it (src/draco.js)
const DR = join(three, 'examples/jsm/libs/draco/gltf/');
writeFileSync(
  join(root, 'src/draco-bin.js'),
  "// generated by scripts/build.mjs from three.js's copy of Google's Draco decoder (Apache-2.0)\nexport const DRACO_WRAPPER = "
    + JSON.stringify(readFileSync(DR + 'draco_wasm_wrapper.js', 'utf8'))
    + ';\nexport const DRACO_WASM = "'
    + readFileSync(DR + 'draco_decoder.wasm').toString('base64')
    + '";\n'
);

// three.js carries three libraries of other people inside its own package; their licences are said here in full
const mit = (who) =>
  `Copyright (c) ${who}\n\n`
  + readFileSync(join(three, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n').split('\n').slice(3).join('\n').trim();
const apache = readFileSync(join(root, 'node_modules/@tauri-apps/api/LICENSE-APACHE-2.0'), 'utf8');
const before = [
  {
    title: 'Draco 3D data decompression (Google), inside three.js: examples/jsm/libs/draco. Decoding only.',
    text: 'Copyright 2017 The Draco Authors.\n\n' + apache,
  },
  {
    title: 'meshoptimizer decoder (Arseny Kapoulkine), inside three.js: examples/jsm/libs/meshopt_decoder.module.js',
    text: mit('2016-2026 Arseny Kapoulkine'),
  },
  {
    title: 'fflate (Arjun Barrett), inside three.js: examples/jsm/libs/fflate.module.js',
    text: mit('2023 Arjun Barrett'),
  },
];

await buildTool({
  root,
  name: 'DotAny 3D',
  // the recent-files rows' icon, then the tool's own buttons
  icons: {
    file: 'box',
    parts: 'layers',
    play: 'play',
    pause: 'pause',
    ruler: 'ruler',
    slice: 'scissors-line-dashed',
    flip: 'flip-vertical-2',
    eye: 'eye',
    hidden: 'eye-off',
    focus: 'scan-eye',
  },
  notices: { before },
});
