// Builds a tool's page into its dist/. A tool's own scripts/build.mjs calls buildTool with what is its own.
// The licence page's long list is a separate file, loaded when needed. The family's fonts aren't built in: every
// program reads the one shared copy (shared/rust/src/fonts.rs, shared/web/fonts.js).
import { generate } from './notices.mjs';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SHARED = join(dirname(fileURLToPath(import.meta.url)), '..');

// Lucide's own drawings, one stroke and one grid, the same as every DotAny tool. These are the family's; a tool adds its own.
export const FAMILY_ICONS = {
  settings: 'settings-2',
  saveAs: 'file-input',
  chevron: 'chevron-down',
  back: 'chevron-left',
  info: 'info',
  alert: 'circle-alert',
  winMin: 'minus',
  winMax: 'square',
  winRestore: 'copy',
  winClose: 'x',
};

/** A package from the tool's own node_modules: shared/ has none of its own, so every tool builds with the versions it installed. */
export const fromTool = async (root, name) =>
  import(pathToFileURL(createRequire(join(root, 'package.json')).resolve(name)).href);

/** Where `@dotany/web` points, and where bare imports in it are found: the same for the build and for the licence count. */
export const bundleOptions = (root) => ({
  alias: { '@dotany/web': join(SHARED, 'web') },
  nodePaths: [join(root, 'node_modules')],
});

/**
 * root: the tool's folder. name: 'DotAny Starter'. icons: { key: lucide name } for the tool's own buttons, with `file`
 * for the recent-files rows. notices: what scripts/notices.mjs adds before the library list (see there).
 */
export async function buildTool({ root, name, icons = {}, notices = {} }) {
  const dist = join(root, 'dist');
  const NAMES = { ...FAMILY_ICONS, ...icons };
  const read = (n) =>
    readFileSync(join(root, `node_modules/lucide-static/icons/${n}.svg`), 'utf8')
      .replace(/<!--[\s\S]*?-->/g, '')
      .match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1]
      .replace(/\s*\n\s*/g, '')
      .trim();
  writeFileSync(
    join(root, 'src/icons.js'),
    '// generated by shared/scripts/build.mjs from lucide-static (ISC licence)\nexport const LUCIDE = '
      + JSON.stringify(Object.fromEntries(Object.entries(NAMES).map(([k, n]) => [k, read(n)])))
      + ';\n'
  );

  rmSync(dist, { recursive: true, force: true });
  mkdirSync(join(dist, 'fonts'), { recursive: true });
  console.log('notices', JSON.stringify(await generate({ root, name, ...notices })));
  const { build } = await fromTool(root, 'esbuild');
  const result = await build({
    entryPoints: [join(root, 'src/main.js')],
    bundle: true,
    splitting: true,
    format: 'esm',
    minify: true,
    target: 'es2022',
    outdir: dist,
    charset: 'utf8',
    legalComments: 'none',
    metafile: true,
    chunkNames: 'chunks/[name]-[hash]',
    ...bundleOptions(root),
  });
  // the family's sheet first, then the tool's own, which only adds
  const css =
    readFileSync(join(SHARED, 'web/family.css'), 'utf8') + '\n\n' + readFileSync(join(root, 'src/styles.css'), 'utf8');
  writeFileSync(join(dist, 'styles.css'), css);
  writeFileSync(
    join(dist, 'index.html'),
    `<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${name}</title>
<link rel="stylesheet" href="styles.css">
<link rel="preload" href="http://dotfont.localhost/StackSansText-wght.ttf" as="font" type="font/ttf" crossorigin>
</head>
<body>
<div id="app"></div>
<script type="module" src="main.js"></script>
</body>
</html>
`
  );
  const sizes = Object.entries(result.metafile.outputs).map(
    ([k, v]) => `${k.replace(/^.*dist[\/]/, '')} ${(v.bytes / 1024).toFixed(0)}KB`
  );
  console.log(sizes.join('\n'));
}
