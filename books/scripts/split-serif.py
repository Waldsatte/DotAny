# Splits Books' reading serif (books/fonts/NotoSerifSC-VF.woff2, SIL OFL 1.1) into pieces by character, so a page loads
# only the pieces whose characters it shows. Every glyph, every weight and every layout feature stays as it is: each
# piece is the same font with fewer characters in it.
#
#   python -I books/scripts/split-serif.py
#
# Needs fontTools and brotli (pip install fonttools brotli). Run it again only when the font changes; the pieces and
# books/fonts/serif/faces.css are committed, and books/scripts/build.mjs puts them in the page.
#
# The pieces:
#   0     everything that isn't a Han character: Latin, digits, every punctuation mark and symbol. Kept together so
#         that marks shaped side by side (the paired punctuation that text-spacing-trim tightens) are in one font.
#   1     GB 2312 level 1: the 3,755 most common characters, nearly every character of a modern book.
#   2     GB 2312 level 2: 3,008 less common ones.
#   3…    every other Han character the font has, in runs of code points.
import os, sys
from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, '..', 'fonts')
SOURCE = os.path.join(FONTS, 'NotoSerifSC-VF.woff2')
OUT = os.path.join(FONTS, 'serif')
FAMILY = 'Noto Serif SC'
RUN = 3000  # Han characters per piece after the two GB 2312 levels


def is_han(c):
    return 0x3400 <= c <= 0x4DBF or 0x4E00 <= c <= 0x9FFF or 0xF900 <= c <= 0xFAFF or 0x20000 <= c <= 0x3FFFF


def gb2312_level(level):
    rows = range(0xB0, 0xD8) if level == 1 else range(0xD8, 0xF8)
    out = []
    for hi in rows:
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode('gb2312')
            except UnicodeDecodeError:
                continue
            out.append(ord(ch))
    return out


def ranges(cps):
    cps = sorted(cps)
    out, start, prev = [], None, None
    for c in cps:
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((start, prev))
            start = prev = c
    out.append((start, prev))
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)


def main():
    cmap = set(TTFont(SOURCE, lazy=True).getBestCmap())
    han = sorted(c for c in cmap if is_han(c))
    level1 = [c for c in gb2312_level(1) if c in cmap]
    level2 = [c for c in gb2312_level(2) if c in cmap]
    taken = set(level1) | set(level2)
    rest = [c for c in han if c not in taken]
    pieces = [sorted(cmap - set(han)), sorted(level1), sorted(level2)] + [rest[i:i + RUN] for i in range(0, len(rest), RUN)]
    assert sum(len(p) for p in pieces) == len(cmap) and len(set().union(*map(set, pieces))) == len(cmap)

    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        os.remove(os.path.join(OUT, f))
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']  # every feature: vertical forms, punctuation widths, everything the page may ask for
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    options.notdef_outline = True
    options.glyph_names = False
    options.prune_unicode_ranges = False
    options.drop_tables = [t for t in options.drop_tables if t != 'BASE']  # the baselines stay as they are
    faces = ['/* generated by books/scripts/split-serif.py: Noto Serif SC in pieces by character (SIL OFL 1.1). The page loads\n'
             '   a piece only when it shows one of its characters; every piece is the whole font\'s glyphs for its characters */']
    for i, cps in enumerate(pieces):
        font = TTFont(SOURCE)
        sub = subset.Subsetter(options)
        sub.populate(unicodes=cps)
        sub.subset(font)
        name = f'NotoSerifSC-{i}.woff2'
        font.flavor = 'woff2'
        font.save(os.path.join(OUT, name))
        size = os.path.getsize(os.path.join(OUT, name))
        print(f'{name}: {len(cps)} characters, {size / 1e6:.2f} MB')
        faces.append(f'@font-face {{ font-family: "{FAMILY}"; src: url("fonts/serif/{name}") format("woff2"); font-weight: 200 900; '
                     f'font-display: block; unicode-range: {ranges(cps)}; }}')
    with open(os.path.join(OUT, 'faces.css'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(faces) + '\n')


if __name__ == '__main__':
    sys.exit(main())
